# @title   （範本，底線開頭的檔案不會被列出）
# @desc    複製這個檔改名就是一個新的 action
# @group   example
# @confirm            <- 加了這行，用瀏覽器開網址會先出確認頁

# ============================================================================
#  metadata 就是開頭的註解：
#    @title    面板上顯示的名稱
#    @desc     說明
#    @group    分組
#    @confirm  用 GET 開網址時先出確認頁，不直接執行。
#              **會造成破壞或不可逆的動作一定要加這行** ——
#              否則瀏覽器預抓、聊天軟體展開連結預覽、Wi-Fi 入口偵測
#              都可能把它觸發掉。
#
#  ⚠ 這個檔案有中文，所以必須存成「UTF-8 with BOM」
#
#  Windows PowerShell 5.1 讀 .ps1 時，沒有 BOM 的 UTF-8 會被當成系統 ANSI。
#  中文裡只要出現破折號之類的字，解析就會壞掉，而且是**安靜地壞掉** ——
#  exit code 還是 0，但後半段程式根本沒執行。
#
#  VS Code：右下角編碼選 "UTF-8 with BOM"。或者整份只寫英文。
#  輸出端不用擔心 —— actiond 會自動判斷 UTF-8 / 系統編碼。
#
#  路徑：用 Split-Path $PSScriptRoot -Parent 取得 caddy 目錄，不要寫死。
#
#  執行身分：**你的 action 預設就是以登入中的使用者身分執行的。** actiond 自己是
#  服務帳號，但它會把每一支 action 交給使用者身分的橋，所以工具找得到、profile
#  是對的、產生的檔案 owner 就是那個使用者。你什麼都不用做。
#
#  沒有人登入的時候，actiond 會退回以服務帳號執行，並在輸出上標一句「尚未登入，
#  這個結果可能不完整」。那樣剛好 —— caddy-* 那幾個 action 不需要使用者，而人不在
#  家的時候正是最需要它們的時候。
#
#  你這支沒有使用者就沒有意義的話（要開他看得見的視窗、要讀他的設定或憑證、
#  要用只裝在他帳號下的工具、要寫進只有他有權限的目錄），在上面加一行：
#
#      # @only-when-logged-on
#
#  那樣沒人登入時 actiond 會直接回錯誤、不執行 —— 比跑出一個看起來成功的空答案好，
#  因為使用者分不出「真的沒東西」和「我看不到你的東西」。
# ============================================================================

Write-Output "hello from action"
exit 0
